// Headless validation of the physics core. Prints a report and writes
// docs/physics-validation.md.  Run:  npm run test:physics
import { connectedTanks, ventTanks, tiltTanks, doorDemo, boatDemo, frameRateTest, convergenceTest, repeatabilityTest, detachmentTest, glassTest, ledgerTest } from '../src/physics2/demos.js';
import { writeFileSync } from 'fs';

const dt = 1 / 240;
const run = (S, seconds) => { const n = Math.round(seconds / dt); for (let i = 0; i < n; i++) S.step(dt); return S.checks(); };
const sections = [];
const t0 = Date.now();
sections.push(['1. Two connected tanks: transfer, conservation, momentum', run(connectedTanks(), 60)]);
sections.push(['2. Sealed vs vented tank: air-pressure coupling', run(ventTanks(), 900)]);
sections.push(['3. Tilting part-filled containers: free surface & stability', run(tiltTanks(), 40)]);
sections.push(['4a. Hinged door, opening toward the dry room', run(doorDemo('b'), 240)]);
sections.push(['4b. Hinged door, opening into the flooding room', run(doorDemo('a'), 240)]);
sections.push(['5. Lowering a loaded lifeboat unevenly', run(boatDemo(), 110)]);
const fr = frameRateTest(20);
sections.push(['6a. Frame-rate independence (fixed 1/240 s steps)', [
  ...fr.map(r => ({ name: `${r.label}: ${r.frames} frames, ${r.steps} steps`, pass: r.hash === fr[0].hash, value: r.hash, target: fr[0].hash })),
]]);
const rp = repeatabilityTest();
sections.push(['6b. Repeatability (same machine, same step)', [{ name: 'Two identical runs give bit-identical state', pass: rp[0] === rp[1], value: rp.join(' / '), target: 'equal' }]]);
const cv = convergenceTest();
const order = (k) => { const e = cv.map(r => r[k]); const o = []; for (let i = 1; i < e.length; i++) o.push(Math.log2(e[i - 1] / Math.max(1e-15, e[i]))); return o; };
sections.push(['6c. Timestep convergence (vs 1/960 s reference, t = 12 s)', [
  ...cv.map(r => ({ name: `dt = 1/${Math.round(1 / r.dt)} s`, pass: true, value: `tank ${r.errTankLevel.toExponential(1)} m, door-room ${r.errDoorRoom.toExponential(1)} m, boat ${r.errBoatZ.toExponential(1)} m`, target: '' })),
  { name: 'Errors shrink as the step shrinks', pass: cv[3].errTankLevel < cv[0].errTankLevel && cv[3].errBoatZ < cv[0].errBoatZ, value: `observed order (tank) ${order('errTankLevel').map(x => x.toFixed(2)).join(', ')}`, target: 'decreasing' },
]]);
sections.push(['Extras: detachment, glass, mass ledger', [...detachmentTest(), ...glassTest(), ...ledgerTest()]]);

let md = `# Physics validation report\n\nGenerated by \`npm run test:physics\` (${new Date().toISOString().slice(0, 10)}). Fixed step 1/240 s unless stated. Wall time ${((Date.now() - t0) / 1000).toFixed(1)} s.\n\n`;
let fails = 0, total = 0;
for (const [title, checks] of sections) {
  console.log('\n' + title);
  md += `## ${title}\n\n| Check | Result | Value | Expected | Note |\n|---|---|---|---|---|\n`;
  for (const c of checks) {
    total++; if (!c.pass) fails++;
    console.log(`  ${c.pass ? 'PASS' : 'FAIL'}  ${c.name}: ${c.value}  (expected ${c.target})${c.note ? '  - ' + c.note : ''}`);
    md += `| ${c.name} | ${c.pass ? 'pass' : '**FAIL**'} | ${c.value} | ${c.target} | ${c.note || ''} |\n`;
  }
  md += '\n';
}
md += `**${total - fails} of ${total} checks pass.**\n\nReproducibility limits: results are bit-identical across frame rates and repeated runs on the same JavaScript engine. Different engines or CPUs may differ in the last bits of transcendental functions (Math.sin, Math.exp), so cross-platform agreement is to round-off, not bit-exact.\n`;
writeFileSync('docs/physics-validation.md', md);
console.log(`\n${total - fails}/${total} checks pass`);
process.exitCode = fails ? 1 : 0;
