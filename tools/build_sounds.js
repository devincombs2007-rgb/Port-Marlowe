// Embeds every clip in assets/sounds/*.mp3 into src/sounds.js as data URIs (keyed by file name), so the page
// works offline and from a single file. Run: node tools/build_sounds.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'sounds');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.mp3')).sort();
let out = '// Recorded audio. Generated by tools/build_sounds.js from assets/sounds; sources and licences: assets/sounds/README.md\n(function () {\n  const G = (window.GSW = window.GSW || {});\n  G.SOUNDS = {\n';
for (const f of files) out += "    '" + f.slice(0, -4) + "': 'data:audio/mpeg;base64," + fs.readFileSync(path.join(dir, f)).toString('base64') + "',\n";
out += '  };\n})();\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'sounds.js'), out);
console.log(files.length + ' clips, ' + (out.length / 1024).toFixed(0) + ' kB');
