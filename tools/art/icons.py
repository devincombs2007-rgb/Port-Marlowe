def hexrgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def render(name):
    pal, rows = ICONS[name]
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch not in pal:
                raise KeyError(f"{name}: unknown palette key {ch!r}")
            c = pal[ch]
            if c is None:
                continue
            px[x, y] = hexrgb(c) + (255,)
    return img


def main():
    items_dir = ensure(os.path.join(RP, "textures", "items", "hollow"))
    sheet = Image.new("RGBA", (len(ICONS) * 72, 72), (24, 24, 28, 255))
    for i, name in enumerate(ICONS):
        img = render(name)
        img.save(os.path.join(items_dir, f"{name}.png"))
        big = img.resize((64, 64), Image.NEAREST)
        sheet.paste(big, (i * 72 + 4, 4), big)
    ensure(os.path.join(BUILD, "previews"))
    sheet.save(os.path.join(BUILD, "previews", "icons.png"))


if __name__ == "__main__":
    main()
